/**
 * Builds the Kip aperture SVGs from a few parameters:
 *   assets/icon.svg        metal version, used for 64 px and up
 *   assets/icon-small.svg  flat version, used for 16/32 px
 *   src/webview/components/layout/logoPaths.ts  paths for the in-app <Logo>
 * Run `bun run icons` afterwards (it calls this first) to render PNG/ICNS/ICO.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

// ---- Tunables -------------------------------------------------------------
/** Half-diagonal of the outer aperture, in 1024-canvas px. */
const RADIUS = 268;
/** Side pinch: 1 = straight-edged diamond, smaller = sides bow inward, sharper tips. */
const PINCH_LARGE = 0.72;
/** Gentler pinch for 16/32 px so tips survive anti-aliasing. */
const PINCH_SMALL = 0.9;
/** Clockwise tilt of the symbol, in degrees (0 = upright diamond). */
const TILT = 15;
// ---------------------------------------------------------------------------

type P = [number, number];
const root = join(import.meta.dir, "..");
const C = 512;
const PHI = (1 + Math.sqrt(5)) / 2;
const INNER = RADIUS / (PHI * PHI); // hole = outer / phi^2
const RIDGE = INNER + (RADIUS - INNER) / PHI; // bevel ridge at the golden split of the ring

const f = ([x, y]: P) => `${x.toFixed(2)} ${y.toFixed(2)}`;

/** macOS body: 824x824 superellipse (n=5) centred on the canvas, 100 px safe margin. */
function squircle(steps: number, digits: number): string {
  const n = 5;
  const a = 412;
  const pts: string[] = [];
  for (let i = 0; i < steps; i++) {
    const t = (i / steps) * 2 * Math.PI;
    const ct = Math.cos(t);
    const st = Math.sin(t);
    const x = C + a * Math.sign(ct) * Math.abs(ct) ** (2 / n);
    const y = C + a * Math.sign(st) * Math.abs(st) ** (2 / n);
    pts.push(`${x.toFixed(digits)} ${y.toFixed(digits)}`);
  }
  return `M${pts.join("L")}Z`;
}

const rad = (TILT * Math.PI) / 180;
function rotate([x, y]: P): P {
  const dx = x - C;
  const dy = y - C;
  return [
    C + dx * Math.cos(rad) - dy * Math.sin(rad),
    C + dx * Math.sin(rad) + dy * Math.cos(rad),
  ];
}

type Key = "T" | "R" | "B" | "L";
function diamond(h: number): Record<Key, P> {
  return { T: [C, C - h], R: [C + h, C], B: [C, C + h], L: [C - h, C] };
}

function makeShape(pinch: number) {
  const ctrl = (a: P, b: P): P => [
    C + ((a[0] + b[0]) / 2 - C) * pinch,
    C + ((a[1] + b[1]) / 2 - C) * pinch,
  ];
  const curve = (a: P, b: P) => `Q${f(rotate(ctrl(a, b)))} ${f(rotate(b))}`;
  const ring = (q: P[]) =>
    `M${f(rotate(q[0]!))}` +
    q.map((p, i) => curve(p, q[(i + 1) % q.length]!)).join("") +
    "Z";
  const O = diamond(RADIUS);
  const M = diamond(RIDGE);
  const I = diamond(INNER);
  const silhouette = ring([O.T, O.R, O.B, O.L]) + ring([I.T, I.L, I.B, I.R]);
  const face = (a: Record<Key, P>, b: Record<Key, P>, s: Key, e: Key) =>
    `M${f(rotate(a[s]))}${curve(a[s], a[e])}L${f(rotate(b[e]))}${curve(b[e], b[s])}Z`;
  return { silhouette, face, O, M, I };
}

// Light from the top-left. Outer facets catch it on the upper-left; the hole's
// walls face the other way, so its tones are mirrored.
const SIDES: Record<string, [Key, Key]> = {
  tl: ["L", "T"],
  tr: ["T", "R"],
  br: ["R", "B"],
  bl: ["B", "L"],
};
const TONES: Record<string, [dark: string, mid: string, highlight: string]> = {
  "tl-o": ["#D9D5CC", "#FAF9F6", "#FFFFFF"],
  "tr-o": ["#9C978D", "#D8D4CB", "#F4F2EC"],
  "bl-o": ["#6F6B64", "#A8A399", "#D2CEC5"],
  "br-o": ["#3A3834", "#5E5A54", "#8A857C"],
  "tl-i": ["#45423D", "#66625B", "#8C877E"],
  "tr-i": ["#77736B", "#A39E94", "#C9C5BB"],
  "bl-i": ["#A8A399", "#D3CFC6", "#F2F0EA"],
  "br-i": ["#CFCBC2", "#F3F1EB", "#FFFFFF"],
};

const SQ = squircle(720, 2);
const head = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">`;

const large = makeShape(PINCH_LARGE);
let defs = "";
let faces = "";
for (const [side, [s, e]] of Object.entries(SIDES)) {
  for (const layer of ["o", "i"] as const) {
    const id = `${side}-${layer}`;
    const [dark, mid, hi] = TONES[id]!;
    defs +=
      `\n    <linearGradient id="g-${id}" x1="0" y1="0" x2="1" y2="1">` +
      `<stop offset="0" stop-color="${mid}"/><stop offset="0.38" stop-color="${hi}"/>` +
      `<stop offset="0.62" stop-color="${mid}"/><stop offset="1" stop-color="${dark}"/></linearGradient>`;
    const d =
      layer === "o"
        ? large.face(large.O, large.M, s, e)
        : large.face(large.M, large.I, s, e);
    faces += `\n    <path d="${d}" fill="url(#g-${id})"/>`;
  }
}

writeFileSync(
  join(root, "assets", "icon.svg"),
  `${head}
  <!-- Generated by scripts/generate-icon-svg.ts; edit the script, not this file. -->
  <defs>
    <filter id="lift" x="-20%" y="-20%" width="140%" height="150%">
      <feDropShadow dx="0" dy="22" stdDeviation="26" flood-color="#000" flood-opacity="0.75"/>
    </filter>${defs}
  </defs>
  <path d="${SQ}" fill="#141416"/>
  <g filter="url(#lift)">
    <path d="${large.silhouette}" fill="#FAF9F6" fill-rule="evenodd"/>${faces}
  </g>
</svg>
`,
);

const small = makeShape(PINCH_SMALL);
writeFileSync(
  join(root, "assets", "icon-small.svg"),
  `${head}
  <!-- Generated by scripts/generate-icon-svg.ts; edit the script, not this file. -->
  <path d="${SQ}" fill="#141416"/>
  <path d="${small.silhouette}" fill="#FAF9F6" fill-rule="evenodd"/>
</svg>
`,
);

writeFileSync(
  join(root, "src", "webview", "components", "layout", "logoPaths.ts"),
  `// Generated by scripts/generate-icon-svg.ts; edit the script, not this file.
// Coordinates are on the 1024 icon canvas; crop with viewBox="100 100 824 824".
export const SQUIRCLE_PATH =
  "${squircle(96, 0)}";
export const APERTURE_PATH =
  "${small.silhouette}";
`,
);

console.log("Kip icon SVGs generated.");
